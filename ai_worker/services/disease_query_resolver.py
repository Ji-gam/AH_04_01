"""질의에서 대상 질환을 판별해 논문 검색의 메타데이터 필터 값을 만드는 사전.

논문(unstructured 컬렉션의 disease 메타데이터를 가진 문서)은 5대 질환만 담고 있는데, 순수 벡터 검색은 "질환"이
아니라 "운동/음식" 같은 주제 의미에 지배당한다. 실측(2026-07-17): "고혈압에 좋은
운동은?" -> 1위가 당뇨 논문. 점수가 0.34~0.39 좁은 구간에 뭉쳐 임계값으로는 분리할 수
없고, 질환명을 본문에 접두하는 것만으로도 안 잡힌다. 메타데이터 필터가 유일하게 통했다.

이 사전이 하는 일(LLM 호출 0회):
  1. 질의 -> 대상 질환 판별 (고혈압 -> 심장질환+뇌혈관질환)
  2. 그 질환을 메타데이터 필터 값으로 제공 (교차 질환 논문이 아예 안 나옴)

한때 질의 확장어(`expand_query`)도 여기서 제공했다. 한국어 요약 접두를 도입하기 전에는
확장어가 랭킹을 개선했으나(당뇨 논문 1위 -> 5위), 요약 도입 후 골든셋으로 ON/OFF를
측정하니 recall@1·@3이 **완전히 동일**했다 — 요약이 그 역할을 이미 흡수했다. 효과가
측정되지 않는 복잡도라 제거했다(2026-07-17).

LLM 분류기 대신 사전을 쓰는 이유: 스트리밍 채팅 앞단에 LLM 호출을 하나 더 붙이면 첫
토큰까지의 지연이 그만큼 늘고 질문마다 과금된다(T-LLM-7-3-2가 질환 사전 분류를 뺀 이유).
사전은 결정론적이고 즉시이며, "성분명이 식별 안 되면 DUR 검색을 생략한다"는
`retrieve_service.search_documents()`의 기존 패턴과 같은 구조다.

질환명 문자열은 `ingest_papers.SUPPORTED_DISEASES` 및 app/의
`disease_code_mapper.DISEASE_CODE_MAP` 값과 일치해야 한다.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class _DiseaseRule:
    """keywords 중 하나라도 질의에 나타나면 diseases를 대상 질환으로 삼는다."""

    keywords: tuple[str, ...]
    diseases: tuple[str, ...]


# 키워드는 2자 이상만 둔다. "암"/"간" 같은 1자 키워드는 부분 문자열 매칭에서 오탐이
# 심하다("암기", "시간", "인간", "간단"...) — 대신 실제 질문에 쓰이는 복합어를 나열한다.
_RULES: tuple[_DiseaseRule, ...] = (
    _DiseaseRule(
        keywords=(
            "암환자",
            "암세포",
            "항암",
            "종양",
            "유방암",
            "폐암",
            "위암",
            "대장암",
            "전립선암",
            "간암",
            "췌장암",
            "백혈병",
            "암 ",
            "암에",
            "암은",
            "암이",
            "암을",
            "암의",
        ),
        diseases=("암",),
    ),
    _DiseaseRule(
        keywords=("심장", "심근", "협심증", "심부전", "부정맥", "관상동맥", "심혈관", "심장마비"),
        diseases=("심장질환",),
    ),
    # 인지장애/치매 계열을 뇌혈관질환에 붙이는 건 이 컬렉션 한정 판단이다. 알츠하이머성
    # 치매는 엄밀히 뇌혈관질환이 아니지만, 5대 질환만 담은 이 컬렉션에서 인지 관련 논문은
    # 전부 뇌혈관질환 쪽에 있다(골든셋 paper-09 "피질하 혈관성 인지장애"가 여기 해당).
    _DiseaseRule(
        keywords=(
            "뇌졸중",
            "중풍",
            "뇌경색",
            "뇌출혈",
            "뇌혈관",
            "뇌동맥",
            "인지장애",
            "인지기능",
            "치매",
            "혈관성",
            "편마비",
            "반신마비",
        ),
        diseases=("뇌혈관질환",),
    ),
    # 고혈압은 5대 질환에 없지만 심혈관/뇌혈관 논문이 실제로 답이 된다. 이 매핑이 없으면
    # 벡터 검색이 당뇨 논문을 1위로 올린다(실측).
    _DiseaseRule(
        keywords=("고혈압", "혈압"),
        diseases=("심장질환", "뇌혈관질환"),
    ),
    _DiseaseRule(
        keywords=("당뇨", "혈당", "인슐린", "당화혈색소"),
        diseases=("당뇨",),
    ),
    _DiseaseRule(
        keywords=("간질환", "간염", "지방간", "간경변", "간경화", "간기능", "간 건강", "간수치"),
        diseases=("간질환",),
    ),
)


def resolve_diseases(query: str) -> list[str]:
    """질의에서 대상 질환을 판별한다. 못 찾으면 빈 목록을 반환하고, 호출자는 논문 검색을
    생략한다(5대 질환 논문만 있는 컬렉션에서 질환 맥락 없는 질문에 억지로 답을 꺼내면
    무관한 논문이 인용된다).

    사용자 본인 진단 질환으로의 폴백은 두지 않는다 — "오늘 저녁 맛있었어" 같은 질환과
    무관한 발화도 질의에 disease 필터가 안 걸릴 뿐 similarity_search는 여전히 top-k를
    반환하고, threshold(0.40)만으로는 "식사/운동" 같은 주제어가 겹치는 잡담을 걸러내지
    못했다(실측 2026-07-17). 사용자가 이미 진단받은 질환은 어차피 LLM 시스템 프롬프트의
    "질문자 본인 정보"에 항상 실려가므로(`chat_agent._SYSTEM_PROMPT_TEMPLATE`), 답변
    개인화는 이 폴백 없이도 보장된다 — 이 함수가 잃는 건 "질환이 안 드러난 질문에도
    논문을 억지로 찾아 인용하는" 기능뿐이다."""
    matched: list[str] = []
    for rule in _RULES:
        if any(keyword in query for keyword in rule.keywords):
            matched.extend(d for d in rule.diseases if d not in matched)
    return matched
